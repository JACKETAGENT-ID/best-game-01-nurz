/** Total shards across all levels, for the HUD and the win screen. */
export function totalShards() {
  let total = 0;
  for (const level of LEVELS) {
    for (const row of level.map) {
      for (const ch of row) if (ch === 'o') total += 1;
    }
  }
  return total;
}
